/**
 * Правовые документы сервиса.
 *
 * Документы хранятся как структурированные блоки, а не как HTML-строки:
 * это даёт единое оформление, безопасный рендер (без dangerouslySetInnerHTML)
 * и возможность переиспользовать тот же текст в PDF/печати.
 *
 * ВАЖНО: при любом изменении текста документа поднимайте его `version`
 * и `LEGAL_VERSION` в index.ts — от этого зависит фиксация согласий
 * пользователей (таблица user_consents хранит принятую редакцию).
 */

export type LegalBlock =
  /** Заголовок раздела */
  | { t: 'h2'; text: string }
  /** Подзаголовок внутри раздела */
  | { t: 'h3'; text: string }
  /** Абзац. Поддерживает **жирный** и [текст](ссылка). */
  | { t: 'p'; text: string }
  /** Маркированный список */
  | { t: 'ul'; items: string[] }
  /** Выделенная плашка — для существенных предупреждений */
  | { t: 'note'; text: string }
  /** Реквизиты, моноширинным шрифтом */
  | { t: 'req'; items: string[] }

export interface LegalDocument {
  /** Часть URL: /legal/<slug> */
  slug: string
  /** Полное название документа */
  title: string
  /** Короткое название — для ссылок в интерфейсе и футере */
  shortTitle: string
  /** Одно предложение: о чём документ */
  subtitle: string
  /** Редакция в формате YYYY-MM-DD */
  version: string
  /** Дата редакции по-русски — для шапки документа */
  versionLabel: string
  blocks: LegalBlock[]
}
