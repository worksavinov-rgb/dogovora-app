/**
 * Основание полномочий подписанта своего юрлица — в человеческий текст.
 *
 * В Profile.signatorBasis лежит РАЗНОЕ: свободный текст, который человек вписал
 * сам («Свидетельства о регистрации»), и служебные коды, попавшие туда из
 * бывшего раздела «Подписанты» (он записывал в это поле enum вместо текста).
 *
 * Переводили коды в двух местах и по-разному: в party-data только CHARTER и POA,
 * в presentation-content не переводили вовсе. Из-за этого в шапку договора могло
 * уехать «действующего на основании CERTIFICATE». Теперь перевод один на всех.
 *
 * Модуль чистый (без Prisma и React), поэтому годится и серверу, и форме.
 */

const BASIS_TEXT: Record<string, string> = {
  CHARTER: 'Устава',
  POA: 'Доверенности',
  CERTIFICATE: 'Свидетельства о государственной регистрации',
  REGULATION: 'Положения',
  // OTHER осмысленного текста не несёт: «на основании иного документа» в договоре
  // выглядит нелепо, поэтому лучше пусто — шапка подставит прочерк.
  OTHER: '',
}

/** Код → текст. Свободный текст возвращается как есть. */
export function signatoryBasisText(value: string | null | undefined): string | null {
  if (!value) return null
  const text = BASIS_TEXT[value.trim().toUpperCase()]
  if (text === undefined) return value
  return text || null
}
