// Санитарный golden-тест convertToDocx: длинный HTML-договор (13 разделов,
// реквизиты, 2 приложения с таблицей) → DOCX → распаковка → word/document.xml.
// Главный инвариант: при выгрузке в Word НЕ теряется текст (уже было 4 регрессии).
import { describe, it, expect } from 'vitest'
import { convertToDocx } from '@shared/formatting/html-docx-converter'
import { readDocumentXml, docxPlainText, htmlPlainText, compact } from './docx-utils'

// ─── Генерация фикстуры: реалистичный длинный договор ─────────────────────────

const CUSTOMER_INN = '7707083893'
const EXECUTOR_INN = '502906602876'

const SECTION_TITLES = [
  'ПРЕДМЕТ ДОГОВОРА',
  'ПРАВА И ОБЯЗАННОСТИ СТОРОН',
  'СТОИМОСТЬ УСЛУГ И ПОРЯДОК РАСЧЁТОВ',
  'ПОРЯДОК СДАЧИ И ПРИЁМКИ УСЛУГ',
  'ОТВЕТСТВЕННОСТЬ СТОРОН',
  'ОБСТОЯТЕЛЬСТВА НЕПРЕОДОЛИМОЙ СИЛЫ',
  'КОНФИДЕНЦИАЛЬНОСТЬ',
  'ИНТЕЛЛЕКТУАЛЬНАЯ СОБСТВЕННОСТЬ',
  'ПОРЯДОК РАЗРЕШЕНИЯ СПОРОВ',
  'СРОК ДЕЙСТВИЯ ДОГОВОРА',
  'ПОРЯДОК ИЗМЕНЕНИЯ И РАСТОРЖЕНИЯ ДОГОВОРА',
  'ЗАКЛЮЧИТЕЛЬНЫЕ ПОЛОЖЕНИЯ',
]

/** Строит длинный договор: преамбула, 13 разделов с пунктами N.N, реквизиты, 2 приложения. */
function buildLongContractHtml(): string {
  const parts: string[] = []

  // Преамбула
  parts.push('<h1>ДОГОВОР № 42-2025 на оказание услуг по организации и проведению мероприятий</h1>')
  parts.push('<p>г. Москва, 1 февраля 2025 г.</p>')
  parts.push(
    '<p>Общество с ограниченной ответственностью «Ромашка», именуемое в дальнейшем «Заказчик», ' +
    'в лице Генерального директора Иванова Ивана Ивановича, действующего на основании Устава, с одной стороны, и ' +
    'Индивидуальный предприниматель Савинов Павел Андреевич, именуемый в дальнейшем «Исполнитель», ' +
    'действующий на основании ОГРНИП 323508100000001, с другой стороны, совместно именуемые «Стороны», ' +
    'заключили настоящий Договор о нижеследующем:</p>',
  )

  // 12 содержательных разделов с пунктами N.N (тексты достаточно длинные,
  // чтобы суммарный объём превысил 15 000 знаков)
  SECTION_TITLES.forEach((title, i) => {
    const n = i + 1
    parts.push(`<h2>${n}. ${title}</h2>`)
    for (let j = 1; j <= 7; j++) {
      parts.push(
        `<p>${n}.${j}. Стороны согласовали, что в рамках раздела «${title}» надлежащее исполнение обязательств ` +
        `подтверждается документально, а именно актами, уведомлениями и перепиской Сторон; при этом каждая из Сторон ` +
        `обязуется действовать добросовестно, разумно и осмотрительно, не допуская нарушения прав и законных интересов ` +
        `другой Стороны, третьих лиц и требований применимого законодательства Российской Федерации (пункт ${n}.${j}).</p>`,
      )
    }
  })

  // Раздел 13 — реквизиты (двухколоночный системный блок)
  parts.push('<h2>13. МЕСТО НАХОЖДЕНИЯ И БАНКОВСКИЕ РЕКВИЗИТЫ СТОРОН</h2>')
  parts.push(
    '<div class="doc-requisites">' +
    '<div class="doc-requisites-party">' +
    '<p><strong>Заказчик:</strong></p><p>ООО «Ромашка»</p>' +
    `<p>ИНН: ${CUSTOMER_INN}</p><p>КПП: 770701001</p><p>БИК: 044525225</p>` +
    '<p>Р/счет: 40702810400000012345</p><p>К/счет: 30101810400000000225</p>' +
    '</div>' +
    '<div class="doc-requisites-party">' +
    '<p><strong>Исполнитель:</strong></p><p>ИП Савинов Павел Андреевич</p>' +
    `<p>ИНН: ${EXECUTOR_INN}</p><p>БИК: 044525974</p>` +
    '<p>Р/счет: 40802810900001234567</p><p>К/счет: 30101810145250000974</p>' +
    '</div>' +
    '</div>',
  )

  // Приложение №1 — заявка с таблицей
  parts.push('<h2>ПРИЛОЖЕНИЕ №1 к Договору № 42-2025</h2>')
  parts.push('<h3>ЗАЯВКА на оказание услуг</h3>')
  parts.push('<p>Наименование мероприятия: ежегодная отраслевая конференция. Дата проведения: 12 октября 2025 года. Место проведения: конгресс-центр, г. Москва.</p>')
  parts.push(
    '<table><thead><tr><th>№</th><th>Наименование услуги</th><th>Количество</th><th>Стоимость, руб.</th></tr></thead>' +
    '<tbody>' +
    '<tr><td>1</td><td>Аренда конференц-зала на 200 мест</td><td>1</td><td>150 000</td></tr>' +
    '<tr><td>2</td><td>Техническое сопровождение (звук, свет, трансляция)</td><td>2</td><td>80 000</td></tr>' +
    '<tr><td>3</td><td>Кейтеринг для участников</td><td>200</td><td>240 000</td></tr>' +
    '</tbody></table>',
  )

  // Приложение №2 — форма акта
  parts.push('<h2>ПРИЛОЖЕНИЕ №2 к Договору № 42-2025</h2>')
  parts.push('<h3>ФОРМА АКТА сдачи-приёмки оказанных услуг</h3>')
  parts.push('<p>Исполнитель оказал, а Заказчик принял услуги по организации и проведению мероприятия в полном объёме. Стороны взаимных претензий по объёму, качеству и срокам оказания услуг не имеют.</p>')
  parts.push('<p>Стоимость оказанных услуг составляет сумму, согласованную Сторонами в Заявке, НДС не облагается в связи с применением Исполнителем упрощённой системы налогообложения.</p>')

  return parts.join('\n')
}

// ─── Тесты ────────────────────────────────────────────────────────────────────

describe('convertToDocx — санитарный golden-тест конвейера', () => {
  it('длинный договор конвертируется без потери текста (≥ 98% символов), приложения и ИНН на месте', async () => {
    const html = buildLongContractHtml()

    // Предусловие фикстуры: договор действительно длинный (≥ 15 000 знаков текста)
    const sourceText = htmlPlainText(html)
    expect(sourceText.length).toBeGreaterThanOrEqual(15000)

    const buffer = await convertToDocx(html, { title: 'Договор № 42-2025' })
    const xml = await readDocumentXml(buffer)
    const docText = docxPlainText(xml)

    // Инвариант 1: потеря текста не более 2% (сравниваем без пробелов —
    // конвертер легально нормализует пробельные символы)
    const srcLen = compact(sourceText).length
    const docLen = compact(docText).length
    expect(docLen).toBeGreaterThanOrEqual(Math.floor(srcLen * 0.98))

    // Инвариант 2: оба приложения дошли до Word
    expect(docText).toContain('ПРИЛОЖЕНИЕ №1')
    expect(docText).toContain('ПРИЛОЖЕНИЕ №2')

    // Инвариант 3: ИНН обеих сторон присутствуют
    expect(docText).toContain(CUSTOMER_INN)
    expect(docText).toContain(EXECUTOR_INN)

    // Контроль краёв: первый и последний содержательные пункты не потерялись
    expect(docText).toContain('1.1. Стороны согласовали')
    expect(docText).toContain('упрощённой системы налогообложения')
  })

  it('содержимое таблицы приложения (услуги и суммы) сохраняется в DOCX', async () => {
    const html = buildLongContractHtml()
    const buffer = await convertToDocx(html)
    const docText = docxPlainText(await readDocumentXml(buffer))

    expect(docText).toContain('Аренда конференц-зала на 200 мест')
    expect(docText).toContain('Техническое сопровождение')
    expect(docText).toContain('Кейтеринг для участников')
    expect(docText).toContain('240 000')
  })
})
